const dictionaries: Record<Lang, Dictionary> = { en, ru, uz }

export const LANGS: Lang[] = ["en", "ru", "uz"]

export type TranslateVars = Record<string, string | number>

export function translate(lang: Lang, key: string, vars?: TranslateVars): string {
  const template = dictionaries[lang][key as TranslationKey] ?? en[key as TranslationKey] ?? key
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match))
}

export function useT() {
  const { lang } = useAppStore()
  const t = useCallback((key: string, vars?: TranslateVars) => translate(lang, key, vars), [lang])
  return { t, lang }
}
